/**
 * Adapter between the convert screen and the layout / Goodnotes modules. The screen only talks
 * to `ConvertDeps`; this file is the single place that knows the other modules' signatures:
 *   layoutText(text, glyphs, opts) → { doc, missing }      (src/layout/index.ts)
 *   renderPreviewSvg(doc, page, paper) → SVG markup string (src/layout/index.ts)
 *   writeGoodnotes(template, doc) → bytes                  (src/goodnotes/index.ts)
 */
import { layoutText, renderPreviewSvg } from '../layout/index.ts';
import { writeGoodnotes } from '../goodnotes/index.ts';
import { PAPER_A4_RULED, type DocumentContent, type Glyph } from '../types.ts';

export interface ConvertOptions {
  headingWidthMm: number;
  bodyWidthMm: number;
}

export interface ConvertDeps {
  layout(text: string, glyphs: Glyph[], opts: ConvertOptions): { doc: DocumentContent; missing: string[] };
  /** SVG markup (string, generated by our own code from numbers — no user text) or an element. */
  preview(doc: DocumentContent, page: number): string | Element;
  /** Goodnotes file bytes. */
  write(template: Uint8Array, doc: DocumentContent): Promise<Blob>;
  templateUrl: string;
}

function toBlob(data: unknown): Blob {
  if (data instanceof Blob) return data;
  if (data instanceof Uint8Array) return new Blob([data.slice().buffer as ArrayBuffer]);
  if (data instanceof ArrayBuffer) return new Blob([data]);
  throw new Error('writeGoodnotes lieferte ein unbekanntes Format');
}

export const convertDeps: ConvertDeps = {
  layout: (text, glyphs, opts) => {
    const r = layoutText(text, glyphs, { headingWidthMm: opts.headingWidthMm, bodyWidthMm: opts.bodyWidthMm });
    return { doc: r.doc, missing: r.missing };
  },
  preview: (doc, page) => renderPreviewSvg(doc, page, PAPER_A4_RULED),
  write: async (template, doc) => toBlob(await writeGoodnotes(template, doc)),
  templateUrl: `${import.meta.env.BASE_URL}template/a4-ruled-yellow.goodnotes`,
};
