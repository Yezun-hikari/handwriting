/**
 * Adapter between the convert screen and the layout / Goodnotes modules. The screen only talks
 * to `ConvertDeps`; this file is the single place that knows the other modules' signatures:
 *   layoutText(text, glyphs, opts) → { doc, missing }      (src/layout/index.ts)
 *   renderPreviewSvg(doc, page, paper) → SVG markup string (src/layout/index.ts)
 *   buildGoodnotesFile(req, onProgress) → bytes            (src/ui/convert-build.ts, in a Web Worker)
 */
import { layoutText, renderPreviewSvg } from '../layout/index.ts';
import { PAPERS, type DocumentContent, type Glyph, type PaperId } from '../types.ts';
import { buildGoodnotesFile, type BuildProgress, type BuildRequest, type WorkerReply } from './convert-build.ts';

export interface ConvertOptions {
  headingWidthMm: number;
  bodyWidthMm: number;
  paper: PaperId;
}

export interface ConvertDeps {
  layout(text: string, glyphs: Glyph[], opts: ConvertOptions): { doc: DocumentContent; missing: string[] };
  /** Page count and missing characters of the whole text, without producing strokes (cheap). */
  measure(text: string, glyphs: Glyph[], opts: ConvertOptions): { pages: number; missing: string[] };
  /** SVG markup (string, generated by our own code from numbers — no user text) or an element. */
  preview(doc: DocumentContent, page: number, paper: PaperId): string | Element;
  /** Full layout + Goodnotes file, off the main thread where possible. Rejects with an AbortError when aborted. */
  build(req: BuildRequest, onProgress?: (p: BuildProgress) => void, signal?: AbortSignal): Promise<Blob>;
  templateUrl(paper: PaperId): string;
}

const abortError = (): Error => new DOMException('Abgebrochen', 'AbortError');

/** Synchronous fallback: same work on the main thread (tests, browsers without module workers). */
export async function buildInline(req: BuildRequest, onProgress?: (p: BuildProgress) => void, signal?: AbortSignal): Promise<Blob> {
  if (signal?.aborted) throw abortError();
  const r = await buildGoodnotesFile(req, onProgress);
  if (signal?.aborted) throw abortError();
  return new Blob([r.bytes as Uint8Array<ArrayBuffer>]);
}

let nextId = 1;

/** Runs the build in a module worker (one worker per build, terminated afterwards or on abort). */
export function buildInWorker(
  req: BuildRequest,
  onProgress?: (p: BuildProgress) => void,
  signal?: AbortSignal,
  createWorker: () => Worker = () => new Worker(new URL('./convert-worker.ts', import.meta.url), { type: 'module' }),
): Promise<Blob> {
  if (signal?.aborted) return Promise.reject(abortError());
  let worker: Worker;
  try {
    worker = createWorker();
  } catch {
    return buildInline(req, onProgress, signal); // e.g. module workers unsupported
  }
  const id = nextId++;
  return new Promise<Blob>((resolve, reject) => {
    const finish = (): void => {
      worker.terminate();
      signal?.removeEventListener('abort', onAbort);
    };
    const onAbort = (): void => {
      finish();
      reject(abortError());
    };
    signal?.addEventListener('abort', onAbort);
    let started = false;
    worker.onmessage = (e: MessageEvent<WorkerReply>) => {
      const m = e.data;
      if (m.id !== id) return;
      started = true;
      if (m.kind === 'progress') onProgress?.(m.progress);
      else if (m.kind === 'done') {
        finish();
        resolve(new Blob([m.result.bytes as Uint8Array<ArrayBuffer>]));
      } else {
        finish();
        reject(new Error(m.message));
      }
    };
    worker.onerror = (e) => {
      e.preventDefault();
      finish();
      // The worker script itself failed to load: do the work here instead of failing the download.
      if (!started) buildInline(req, onProgress, signal).then(resolve, reject);
      else reject(new Error(e.message || 'Hintergrundprozess abgebrochen'));
    };
    // Copy the template so the caller's buffer survives the transfer.
    const template = req.template.slice();
    worker.postMessage({ id, req: { ...req, template } }, [template.buffer]);
  });
}

export const convertDeps: ConvertDeps = {
  layout: (text, glyphs, opts) => {
    const r = layoutText(text, glyphs, { headingWidthMm: opts.headingWidthMm, bodyWidthMm: opts.bodyWidthMm, paper: PAPERS[opts.paper] });
    return { doc: r.doc, missing: r.missing };
  },
  measure: (text, glyphs, opts) => {
    const r = layoutText(text, glyphs, { ...opts, paper: PAPERS[opts.paper], measureOnly: true });
    return { pages: r.doc.pages.length, missing: r.missing };
  },
  preview: (doc, page, paper) => renderPreviewSvg(doc, page, PAPERS[paper]),
  build: (req, onProgress, signal) =>
    typeof Worker === 'function' ? buildInWorker(req, onProgress, signal) : buildInline(req, onProgress, signal),
  templateUrl: (paper) => `${import.meta.env.BASE_URL}template/${PAPERS[paper].file}.goodnotes`,
};
